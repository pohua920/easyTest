package cn.com.sinosoft.saa.vo;


public class SaaRiskVO{
	private String riskCode;
	private String riskCName;
	private String upperRiskCode;
	public String getRiskCode() {
		return riskCode;
	}
	public void setRiskCode(String riskCode) {
		this.riskCode = riskCode;
	}
	public String getRiskCName() {
		return riskCName;
	}
	public void setRiskCName(String riskCName) {
		this.riskCName = riskCName;
	}
	public String getUpperRiskCode() {
		return upperRiskCode;
	}
	public void setUpperRiskCode(String upperRiskCode) {
		this.upperRiskCode = upperRiskCode;
	}
	
	
}
